const korean = Object.fromEntries(
  Object.entries(english).map(([ko, en]) => [en, ko]),
);
export function createTranslator(
  locale: Locale = "en-US",
  overrides: Record<string, string> = {},
) {
  return (source: string) => {
    const key = source as keyof typeof english;
    const en = english[key] ?? source;
    const ko = korean[source] ?? source;
    return overrides[en] ?? (locale === "ko-KR" ? ko : en);
  };
}
